// Generates a Godot 4 .tscn scene file from the console's current state.
const esc = s => String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"')

function hexToGodot(hex) {
  const m = /^#?([0-9a-f]{6})$/i.exec(String(hex || '').trim())
  if (!m) return 'Color(0.545, 0.361, 0.965, 1)'
  const n = parseInt(m[1], 16)
  const r = ((n >> 16) & 255) / 255
  const g = ((n >> 8) & 255) / 255
  const b = (n & 255) / 255
  return `Color(${r.toFixed(3)}, ${g.toFixed(3)}, ${b.toFixed(3)}, 1)`
}

export function buildTscn(state) {
  const tiles = Array.isArray(state.tiles) ? state.tiles.slice(0, 120) : []
  const wallpaper = esc(typeof state.wallpaperId === 'string' ? state.wallpaperId : 'violet')
  const accent = hexToGodot(typeof state.accent === 'string' ? state.accent : '#8b5cf6')
  const clock = new Date().toLocaleTimeString('en-US', { hour12: false })

  const out = []
  out.push('; Fusion Console scene export — generated by the Fusion Console web app.')
  out.push('; Pair with res://fusion_console.gd, which should expose the')
  out.push('; `wallpaper` and `accent` exported properties used below.')
  out.push('')
  out.push('[gd_scene load_steps=2 format=3 uid="uid://bfusioncnsl1"]')
  out.push('')
  out.push('[ext_resource type="Script" path="res://fusion_console.gd" id="1_fusion"]')
  out.push('')
  out.push('[node name="FusionConsole" type="Control"]')
  out.push('layout_mode = 3')
  out.push('anchors_preset = 15')
  out.push('anchor_right = 1.0')
  out.push('anchor_bottom = 1.0')
  out.push('grow_horizontal = 2')
  out.push('grow_vertical = 2')
  out.push('script = ExtResource("1_fusion")')
  out.push(`wallpaper = "${wallpaper}"`)
  out.push(`accent = ${accent}`)
  out.push('')
  out.push('[node name="Background" type="ColorRect" parent="."]')
  out.push('layout_mode = 1')
  out.push('anchors_preset = 15')
  out.push('anchor_right = 1.0')
  out.push('anchor_bottom = 1.0')
  out.push('grow_horizontal = 2')
  out.push('grow_vertical = 2')
  out.push(`color = ${hexToGodot('#0a0d16')}`)
  out.push('')
  out.push('[node name="Clock" type="Label" parent="."]')
  out.push('layout_mode = 1')
  out.push('anchors_preset = 1')
  out.push('anchor_left = 1.0')
  out.push('anchor_right = 1.0')
  out.push('offset_left = -420.0')
  out.push('offset_top = 24.0')
  out.push('offset_right = -48.0')
  out.push('offset_bottom = 72.0')
  out.push('grow_horizontal = 0')
  out.push(`text = "${esc(clock)}"`)
  out.push(`theme_override_colors/font_color = ${hexToGodot('#eef1f8')}`)
  out.push('theme_override_font_sizes/font_size = 34')
  out.push('horizontal_alignment = 2')
  out.push('')
  out.push('[node name="Library" type="GridContainer" parent="."]')
  out.push('layout_mode = 1')
  out.push('anchors_preset = 15')
  out.push('anchor_right = 1.0')
  out.push('anchor_bottom = 1.0')
  out.push('offset_left = 48.0')
  out.push('offset_top = 140.0')
  out.push('offset_right = -48.0')
  out.push('offset_bottom = -48.0')
  out.push('grow_horizontal = 2')
  out.push('grow_vertical = 2')
  out.push('columns = 6')
  out.push('theme_override_constants/h_separation = 20')
  out.push('theme_override_constants/v_separation = 20')
  out.push('')
  tiles.forEach((t, i) => {
    out.push(`[node name="Tile${i}" type="Button" parent="Library"]`)
    out.push('layout_mode = 2')
    out.push('custom_minimum_size = Vector2(136, 136)')
    out.push(`text = "${esc(t.name || `Item ${i + 1}`)}"`)
    out.push('')
  })
  return out.join('\n') + '\n'
}
